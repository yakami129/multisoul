// ─── Glyph pools ──────────────────────────────────────────────────────────────

const HEX = '0123456789ABCDEF';
const BRAILLE = '⠿⠾⣿⣾⢿⡿⣻⢻⡻⠻⣽⢽⡽⠽⣺⢺⡺⠺⣹⢹⡹⠹⣸⢸⡸⢰⡰⠰⣯⢯⡯⣮⢮⡮';
const BLOCKS = '░▒▓█▄▀■□▪';

const pick = (s: string) => s[Math.floor(Math.random() * s.length)];
// Sparse static — most cells empty, with occasional glyph for a "signal noise" feel
export function noiseLine(source: string): string {
  return [...source]
    .map((ch) => {
      if (ch === ' ' || ch === '⠀') return ch;
      const r = Math.random();
      if (r < 0.55) return '⠀';
      if (r < 0.85) return pick(BRAILLE);
      if (r < 0.97) return pick(HEX);
      return pick(BLOCKS);
    })
    .join('');
}

// Partial decode — rate% correct chars, rest are random braille (signal-lock effect)
export function partialDecode(source: string, rate: number): string {
  return [...source]
    .map((ch) => {
      if (ch === ' ' || ch === '⠀') return ch;
      return Math.random() < rate ? ch : pick(BRAILLE);
    })
    .join('');
}

export function randomHexAddr(): string {
  let a = '';
  for (let i = 0; i < 8; i++) a += pick(HEX);
  return `0x${a.slice(0, 4)}_${a.slice(4)}`;
}

